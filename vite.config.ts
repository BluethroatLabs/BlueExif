/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Production Content-Security-Policy: the app may load its own code and read
 * local blobs, but it cannot talk to any server — a hard guarantee that files
 * never leave the device. (Not applied in dev, where Vite needs HMR sockets.)
 */
function contentSecurityPolicy(): Plugin {
  const csp = [
    "default-src 'self'",
    "script-src 'self'",
    "worker-src 'self' blob:",
    "style-src 'self'",
    "style-src-attr 'none'",
    "img-src 'self' blob: data:",
    "media-src 'self' blob:",
    "font-src 'self'",
    "manifest-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  return {
    name: 'blueexif-csp',
    apply: 'build',
    transformIndexHtml: (html) =>
      html.replace('<meta charset="UTF-8" />', `<meta charset="UTF-8" />\n    <meta http-equiv="Content-Security-Policy" content="${csp}" />`),
  };
}

/**
 * Emits sw.js precaching every built asset, so BlueExif keeps working with no
 * network at all after the first visit.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'blueexif-offline',
    apply: 'build',
    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const publicFiles = [
        'favicon.svg',
        'theme-boot.js',
        'manifest.webmanifest',
        'icon-192.png',
        'icon-512.png',
        'icon-maskable-192.png',
        'icon-maskable-512.png',
        'apple-touch-icon.png',
      ];
      const files = ['./', ...assets.map((f) => `./${f}`), ...publicFiles.map((f) => `./${f}`)];
      // Version from file *contents*, so a change to any unhashed public file
      // (e.g. theme-boot.js) still ships a new worker and refreshes the cache.
      const hash = createHash('sha256');
      for (const name of assets.sort()) {
        const out = bundle[name];
        hash.update(name).update(out.type === 'chunk' ? out.code : out.source);
      }
      for (const f of publicFiles) hash.update(f).update(readFileSync(join(import.meta.dirname, 'public', f)));
      const version = hash.digest('hex').slice(0, 12);
      const source = `// Generated by vite.config.ts — offline support for BlueExif.
// The app shell is fetched network-first (a new deploy shows up immediately)
// and cached for offline use; everything else is cache-first. Only real app
// shell HTML is ever stored as the shell.
const PREFIX = 'blueexif-';
const CACHE = PREFIX + '${version}';
const FILES = ${JSON.stringify(files)};
const SHELL = new URL('./', self.location).pathname;
const isShell = (url) => {
  const p = new URL(url).pathname;
  return p === SHELL || p === SHELL + 'index.html';
};
const isHtml = (res) => (res.headers.get('content-type') || '').includes('text/html');
// This build's copy first: caches.match alone searches the oldest cache first,
// which would serve the previous build's unhashed files (manifest, icons).
const cached = (req) =>
  caches.open(CACHE)
    .then((c) => c.match(req, { ignoreSearch: true }))
    .then((hit) => hit || caches.match(req, { ignoreSearch: true }));

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  // Keep the previous build's cache one more generation: a tab still running
  // the old build can then lazy-load its chunks (cached() searches every
  // cache) instead of receiving HTML for a file the new deploy removed.
  e.waitUntil(
    caches.keys()
      .then((keys) => {
        const old = keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE);
        return Promise.all(old.slice(0, -1).map((k) => caches.delete(k)));
      })
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req).then((res) => {
        if (res.ok && isShell(req.url) && isHtml(res)) {
          const copy = res.clone();
          e.waitUntil(caches.open(CACHE).then((c) => c.put('./', copy)));
        }
        return res;
      }).catch(() =>
        cached(req)
          .then((hit) => hit || (isShell(req.url) ? cached('./') : undefined))
          .then((hit) => hit || Response.error()),
      ),
    );
    return;
  }
  e.respondWith(
    cached(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok && res.type === 'basic' && !isHtml(res)) {
        const copy = res.clone();
        e.waitUntil(caches.open(CACHE).then((c) => c.put(req, copy)));
      }
      return res;
    })),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

/**
 * `vite build --mode single`: one self-contained blueexif.html. Scripts, styles,
 * fonts, images, the whole engine (with pdf-lib) and pdf.js are inlined; inline
 * code is allowed by SHA-256 hash and the page may not open any connection at
 * all. The engine and pdf.js run in-page (see src/app/workerFactory.single.ts
 * and src/app/pdfPreview.worker.single.ts) because browsers refuse Blob
 * workers on file:// pages.
 */
function singleFile(): Plugin {
  const sha = (text: string) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
  // Keep inlined JavaScript from closing its <script> element. ("<\/" is a valid
  // escape in strings, templates and regexes alike.)
  const escapeScript = (js: string) => js.replace(/<\/(script)/gi, '<\\/$1');
  return {
    name: 'blueexif-single-file',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const page = bundle['index.html'];
      if (!page || page.type !== 'asset') this.error('index.html missing from the bundle');
      let html = String(page.source);
      const scriptHashes: string[] = [];
      const styleHashes: string[] = [];
      const take = (file: string) => {
        const out = bundle[file];
        if (!out) this.error(`${file} missing from the bundle`);
        delete bundle[file];
        return out.type === 'chunk' ? out.code : String(out.source);
      };

      html = html.replace(/<link rel="stylesheet"[^>]*?href="\.\/([^"]+)"[^>]*>/g, (_m, file: string) => {
        const css = take(file);
        styleHashes.push(sha(css));
        return `<style>${css}</style>`;
      });
      html = html.replace(/<script type="module"[^>]*?src="\.\/([^"]+)"[^>]*><\/script>/g, (_m, file: string) => {
        // With code splitting off, dynamic imports (pdf-lib, pdf.js) are inlined but Vite's
        // preload helper keeps its unresolved __VITE_PRELOAD__ placeholder; "no deps" is correct.
        const code = escapeScript(take(file).replaceAll('__VITE_PRELOAD__', 'void 0'));
        // "<!--" followed by "<script" would switch the HTML parser into its
        // double-escaped script state; refuse rather than emit a broken page.
        if (/<!--[\s\S]*<script/i.test(code)) this.error('inlined script contains "<!--" before "<script"');
        scriptHashes.push(sha(code));
        return `<script type="module">${code}</script>`;
      });
      const boot = readFileSync(join(import.meta.dirname, 'public/theme-boot.js'), 'utf8').trim();
      scriptHashes.push(sha(boot));
      html = html.replace(/<script\s+src="\.\/theme-boot\.js"\s*><\/script>/, () => `<script>${boot}</script>`);
      const favicon = readFileSync(join(import.meta.dirname, 'public/favicon.svg')).toString('base64');
      html = html.replace('href="./favicon.svg"', `href="data:image/svg+xml;base64,${favicon}"`);
      // A lone HTML document cannot install itself as an app or ship touch icons.
      html = html.replace(/\s*<link rel="(?:apple-touch-icon|manifest)"[^>]*>/g, '');

      const placeholder = /__VITE_[A-Z_]+__/.exec(html);
      if (placeholder) this.error(`single-file build left an unresolved Vite placeholder: ${placeholder[0]}`);
      const leftover = /(?:src|href)="\.\/[^"]+"/.exec(html);
      if (leftover) this.error(`single-file build still references an external file: ${leftover[0]}`);
      for (const name of Object.keys(bundle)) {
        if (name !== 'index.html' && !name.endsWith('.map')) this.error(`unexpected extra output: ${name}`);
      }

      const csp = [
        "default-src 'none'",
        `script-src ${scriptHashes.join(' ')}`,
        "worker-src 'none'",
        `style-src ${styleHashes.join(' ')}`,
        "style-src-attr 'none'",
        'img-src blob: data:',
        'media-src blob:',
        'font-src data:',
        "connect-src 'none'",
        "manifest-src 'none'",
        "object-src 'none'",
        "base-uri 'none'",
        "form-action 'none'",
      ].join('; ');
      html = html.replace('<meta charset="UTF-8" />', `<meta charset="UTF-8" />\n    <meta http-equiv="Content-Security-Policy" content="${csp}" />`);
      delete bundle['index.html'];
      this.emitFile({ type: 'asset', fileName: 'blueexif.html', source: html });
    },
  };
}

const test = {
  include: ['src/**/*.test.ts'],
  testTimeout: 30_000,
};

export default defineConfig(({ mode }) =>
  mode === 'single'
    ? {
        base: './',
        publicDir: false,
        plugins: [react(), singleFile()],
        resolve: {
          alias: [
            { find: /^\.\/workerFactory$/, replacement: join(import.meta.dirname, 'src/app/workerFactory.single.ts') },
            // pdf.js parses PDFs for page previews on the page, too (no worker asset).
            { find: /^\.\/pdfPreview\.worker$/, replacement: join(import.meta.dirname, 'src/app/pdfPreview.worker.single.ts') },
          ],
        },
        build: {
          target: 'es2022',
          outDir: 'dist-single',
          sourcemap: false,
          cssCodeSplit: false,
          modulePreload: false,
          assetsInlineLimit: () => true,
          rolldownOptions: { output: { codeSplitting: false } },
        },
        test,
      }
    : {
        base: './',
        plugins: [react(), contentSecurityPolicy(), offlineServiceWorker()],
        worker: { format: 'es' },
        build: {
          target: 'es2022',
          sourcemap: true,
        },
        test,
      },
);
